#!/usr/bin/env node
'use strict';
// Signup CLI.
//
// Creates a DeepSeek account (captcha -> e-mail code -> register) and prints
// the resulting userToken. The hard part is the captcha: DeepSeek uses an
// invisible hCaptcha widget whose token is verified server-side, so you need
// either a paid solver or a browser session on a clean IP.
//
// Usage:
//   node scripts/signup.js --email you@gmail.com --mailbox imap
//   CAPTCHA_PROVIDER=capsolver CAPSOLVER_KEY=... node scripts/signup.js \
//       --email you@gmail.com --mailbox imap
//
// Mailbox providers (--mailbox / MAILBOX):
//   imap    read the code from an existing inbox (IMAP_HOST/USER/PASSWORD)
//   http    poll MAILBOX_URL for messages
//   mailtm  disposable inbox (DeepSeek blocks disposable domains — useful only
//           to confirm the domain block, not to actually sign up)
//
// Captcha providers (CAPTCHA_PROVIDER):
//   none      default; will fail with RECAPTCHA_VERIFY_FAILED (useful for tests)
//   capsolver needs CAPSOLVER_KEY
//   2captcha  needs TWOCAPTCHA_KEY
//   browser   drives Chromium (needs playwright-core and CHROME_PATH)

const crypto = require('crypto');
const { requestCode, register, createAccount, SignupError } = require('../lib/signup');
const { solveCaptcha } = require('../lib/captcha');
const { createMailbox } = require('../lib/mailbox');
const { TokenPool } = require('../lib/pool');

function parseArgs(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) {
      const key = a.slice(2);
      const val = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : '1';
      out[key] = val;
    } else {
      out._.push(a);
    }
  }
  return out;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));

  if (args.help) {
    console.log(`Usage: node scripts/signup.js [options]

Options:
  --email <addr>       mailbox address to register (required unless --mailbox mailtm)
  --password <pass>    account password (random if omitted)
  --locale <code>      default en_US
  --region <code>      default US
  --mailbox <kind>     imap | http | mailtm (or MAILBOX env)
  --captcha <prov>     none | capsolver | 2captcha | browser (or CAPTCHA_PROVIDER)
  --persist            append the token to tokens.txt
  --json               print a single JSON object

Env: CAPTCHA_PROVIDER, CAPSOLVER_KEY, TWOCAPTCHA_KEY, CHROME_PATH,
     MAILBOX, MAILBOX_URL, IMAP_HOST, IMAP_PORT, IMAP_USER, IMAP_PASSWORD,
     IMAP_TLS, IMAP_MAILBOX, MAILBOX_EMAIL`);
    process.exit(0);
  }

  const mailboxKind = args.mailbox || process.env.MAILBOX || (args.email ? 'imap' : 'mailtm');
  const captchaProvider = args.captcha || process.env.CAPTCHA_PROVIDER || 'none';
  const locale = args.locale || 'en_US';
  const region = args.region || 'US';
  const password = args.password || crypto.randomBytes(18).toString('base64url');
  const persist = !!args.persist || process.env.DEEPSEEK_TOKEN_PERSIST === '1';

  // For mailtm the address is generated by the provider; for imap/http we need it.
  let mailboxOpts = { kind: mailboxKind };
  if (args.email) {
    process.env.MAILBOX_EMAIL = args.email;
    if (mailboxKind === 'imap' && !process.env.IMAP_USER) process.env.IMAP_USER = args.email;
  }

  const mailbox = await createMailbox(mailboxOpts);
  const email = args.email || mailbox.address;

  if (!args.json) {
    console.error(`mailbox:  ${mailbox.kind}  ${mailbox.address}`);
    console.error(`captcha:  ${captchaProvider}`);
  }

  // Step 1: obtain a captcha token (null for provider "none").
  let captchaToken = null;
  if (captchaProvider !== 'none') {
    if (!args.json) console.error('solving captcha…');
    captchaToken = await solveCaptcha({ provider: captchaProvider, email });
    if (!args.json) console.error(`captcha token: ${captchaToken ? 'ok' : 'none'}`);
  }

  // Step 2: request the verification code.
  if (!args.json) console.error('requesting verification code…');
  await requestCode(email, { captchaToken, locale });

  // Step 3: wait for the code and register.
  if (!args.json) console.error('waiting for the code in the mailbox…');
  const code = await mailbox.waitForCode({ timeoutMs: Number(args.timeout || 180_000) });
  if (!code) {
    console.error('error: no verification code arrived');
    process.exit(1);
  }
  if (!args.json) console.error(`code: ${code}`);

  const account = await register(email, code, password, { locale, region });

  if (persist) {
    try {
      const pool = new TokenPool();
      pool.add(account.token);
    } catch (e) {
      console.error('warning: could not persist token:', e.message);
    }
  }

  const out = {
    token: account.token,
    email: account.email,
    password: account.password,
    deviceId: account.deviceId,
  };

  if (args.json) {
    console.log(JSON.stringify(out));
  } else {
    console.log('\nTOKEN:    ' + out.token);
    console.log('EMAIL:    ' + out.email);
    console.log('PASSWORD: ' + out.password);
  }
}

main().catch((e) => {
  if (e instanceof SignupError) {
    console.error(`error: ${e.message}`);
    if (e.body) console.error(e.body);
  } else {
    console.error('error:', e && e.stack || e);
  }
  process.exit(1);
});
